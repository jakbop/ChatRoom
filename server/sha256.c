/*
 * sha256.c - SHA-256 哈希算法实现
 *
 * 本文件实现了 FIPS 180-4 标准定义的 SHA-256 算法。
 *
 * SHA-256 算法概述：
 *   1. 消息填充：在消息末尾添加 1 位 '1'，若干位 '0'，以及 64 位消息长度，
 *      使填充后的总长度为 512 的倍数
 *   2. 分块处理：将填充后的消息分成 512 位（64 字节）的数据块
 *   3. 消息扩展：将每个 512 位块扩展为 64 个 32 位字（W[0]~W[63]）
 *   4. 压缩计算：对每个块进行 64 轮运算，更新 8 个工作变量（a~h）
 *   5. 输出：将最终的 8 个 32 位状态值拼接为 256 位哈希值
 *
 * 参考文档：
 *   NIST FIPS 180-4: https://nvlpubs.nist.gov/nistpubs/FIPS/NIST.FIPS.180-4.pdf
 */

