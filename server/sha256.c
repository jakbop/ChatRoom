/* ==========================================================================
 * SHA-256 位运算宏定义
 *
 * SHA-256 算法大量使用以下六种位运算，它们是算法的核心非线性组件：
 * ========================================================================== */

/*
 * ROTR(x, n) - 循环右移
 * 将 32 位值 x 向右移动 n 位，右侧溢出的位从左侧补入
 * 例如：ROTR(0b11010000, 3) = 0b00011010
 */
#define ROTR(x, n) (((x) >> (n)) | ((x) << (32 - (n))))

/*
 * CH(x, y, z) - 选择函数（Choice）
 * 对于 x 的每一位：如果该位为 1，则取 y 的对应位；否则取 z 的对应位
 * 即：x ? y : z（按位版本）
 */
#define CH(x, y, z) (((x) & (y)) ^ (~(x) & (z)))

/*
 * MAJ(x, y, z) - 多数函数（Majority）
 * 对于每一位：如果 x, y, z 中至少有两个该位为 1，则结果该位为 1
 * 即：投票表决，少数服从多数
 */
#define MAJ(x, y, z) (((x) & (y)) ^ ((x) & (z)) ^ ((y) & (z)))

/*
 * EP0(x) - 大写 Sigma 0（Σ0），用于工作变量 a 的更新
 * Σ0(x) = ROTR(x, 2) ⊕ ROTR(x, 13) ⊕ ROTR(x, 22)
 */
#define EP0(x) (ROTR(x, 2) ^ ROTR(x, 13) ^ ROTR(x, 22))

/*
 * EP1(x) - 大写 Sigma 1（Σ1），用于工作变量 e 的更新
 * Σ1(x) = ROTR(x, 6) ⊕ ROTR(x, 11) ⊕ ROTR(x, 25)
 */
#define EP1(x) (ROTR(x, 6) ^ ROTR(x, 11) ^ ROTR(x, 25))

/*
 * SIG0(x) - 小写 sigma 0（σ0），用于消息扩展（W[i] 的计算）
 * σ0(x) = ROTR(x, 7) ⊕ ROTR(x, 18) ⊕ (x >> 3)
 */
#define SIG0(x) (ROTR(x, 7) ^ ROTR(x, 18) ^ ((x) >> 3))

/*
 * SIG1(x) - 小写 sigma 1（σ1），用于消息扩展（W[i] 的计算）
 * σ1(x) = ROTR(x, 17) ⊕ ROTR(x, 19) ⊕ (x >> 10)
 */
#define SIG1(x) (ROTR(x, 17) ^ ROTR(x, 19) ^ ((x) >> 10))


/* ==========================================================================
 * sha256_transform() - SHA-256 压缩函数
 *
 * 这是 SHA-256 算法的核心，对一个 512 位（64 字节）的数据块
 * 进行 64 轮压缩计算，更新哈希状态。
 *
 * 算法步骤：
 *   1. 消息扩展：将 16 个 32 位输入字扩展为 64 个字
 *      W[0..15] = 输入块的 16 个大端序 32 位字
 *      W[i] = σ1(W[i-2]) + W[i-7] + σ0(W[i-15]) + W[i-16]  (i = 16..63)
 *
 *   2. 初始化工作变量：
 *      a=H0, b=H1, c=H2, d=H3, e=H4, f=H5, g=H6, h=H7
 *
 *   3. 64 轮压缩运算（每轮 i = 0..63）：
 *      T1 = h + Σ1(e) + CH(e,f,g) + K[i] + W[i]
 *      T2 = Σ0(a) + MAJ(a,b,c)
 *      h=g, g=f, f=e, e=d+T1, d=c, c=b, b=a, a=T1+T2
 *
 *   4. 更新哈希状态：
 *      H0+=a, H1+=b, H2+=c, H3+=d, H4+=e, H5+=f, H6+=g, H7+=h
 *
 * 参数：
 *   ctx   - SHA-256 上下文（state 会被更新）
 *   block - 64 字节的输入数据块
 * ========================================================================== */
static void sha256_transform(SHA256_CTX *ctx, const uint8_t block[64])
{
    /* W[64] - 消息扩展字数组 */
    uint32_t W[64];
    /* 8 个工作变量 */
    uint32_t a, b, c, d, e, f, g, h;
    /* 临时变量 */
    uint32_t t1, t2;
    int i;

    /* ===== 第一步：消息扩展 =====
     * 将 64 字节的输入块解析为 16 个大端序 32 位字 W[0]~W[15]
     * 每个 32 位字由 4 个字节按大端序（高位在前）拼接而成
     */
    for (i = 0; i < 16; i++)
    {
        W[i] = ((uint32_t)block[i * 4] << 24) |       /* 最高字节 */
               ((uint32_t)block[i * 4 + 1] << 16) |   /* 次高字节 */
               ((uint32_t)block[i * 4 + 2] << 8) |    /* 次低字节 */
               ((uint32_t)block[i * 4 + 3]);           /* 最低字节 */
    }

    /* 扩展 W[16]~W[63]：使用 σ0 和 σ1 函数增加非线性 */
    for (i = 16; i < 64; i++)
    {
        W[i] = SIG1(W[i - 2]) + W[i - 7] + SIG0(W[i - 15]) + W[i - 16];
    }

    /* ===== 第二步：初始化工作变量 =====
     * 将当前哈希状态复制到工作变量
     */
    a = ctx->state[0]; b = ctx->state[1]; c = ctx->state[2]; d = ctx->state[3];
    e = ctx->state[4]; f = ctx->state[5]; g = ctx->state[6]; h = ctx->state[7];

    /* ===== 第三步：64 轮压缩运算 =====
     * 每轮使用不同的轮常量 K[i] 和消息字 W[i]
     * T1 是主要的混合项，T2 是辅助混合项
     */
    for (i = 0; i < 64; i++)
    {
        t1 = h + EP1(e) + CH(e, f, g) + K[i] + W[i];
        t2 = EP0(a) + MAJ(a, b, c);
        h = g; g = f; f = e; e = d + t1;
        d = c; c = b; b = a; a = t1 + t2;
    }

    /* ===== 第四步：更新哈希状态 =====
     * 将工作变量加回哈希状态（模 2^32 加法）
     */
    ctx->state[0] += a; ctx->state[1] += b; ctx->state[2] += c; ctx->state[3] += d;
    ctx->state[4] += e; ctx->state[5] += f; ctx->state[6] += g; ctx->state[7] += h;
}


/* ==========================================================================
 * sha256_init() - 初始化 SHA-256 上下文
 *
 * 将上下文清零，并设置初始哈希值。
 * 这些初始值来自 SHA-256 标准（FIPS 180-4），
 * 是前 8 个素数（2,3,5,7,11,13,17,19）平方根的小数部分的前 32 位。
 * ========================================================================== */
void sha256_init(SHA256_CTX *ctx)
{
    ctx->datalen = 0;
    ctx->bitlen = 0;
    ctx->state[0] = 0x6a09e667; ctx->state[1] = 0xbb67ae85;
    ctx->state[2] = 0x3c6ef372; ctx->state[3] = 0xa54ff53a;
    ctx->state[4] = 0x510e527f; ctx->state[5] = 0x9b05688c;
    ctx->state[6] = 0x1f83d9ab; ctx->state[7] = 0x5be0cd19;
}


/* ==========================================================================
 * sha256_update() - 向上下文中填入数据
 *
 * 逐字节将数据填入 data[64] 缓冲区，当缓冲区满（64 字节）时
 * 自动调用 sha256_transform() 处理该数据块。
 *
 * 支持多次调用（流式处理），例如：
 *   sha256_update(&ctx, "Hello", 5);
 *   sha256_update(&ctx, " World", 6);
 *   等价于 sha256_update(&ctx, "Hello World", 11);
 * ========================================================================== */
void sha256_update(SHA256_CTX *ctx, const uint8_t *data, size_t len)
{
    size_t i;
    for (i = 0; i < len; i++)
    {
        /* 将当前字节填入缓冲区 */
        ctx->data[ctx->datalen] = data[i];
        ctx->datalen++;

        /* 缓冲区满（64 字节 = 512 位），处理该数据块 */
        if (ctx->datalen == 64)
        {
            sha256_transform(ctx, ctx->data);
            ctx->bitlen += 512;  /* 已处理 512 位 */
            ctx->datalen = 0;    /* 重置缓冲区 */
        }
    }
}


/* ==========================================================================
 * sha256_final() - 完成哈希计算
 *
 * SHA-256 的填充规则（Merkle-Damgård 填充）：
 *   1. 在消息末尾添加一个字节 0x80（即二进制 10000000）
 *   2. 添加若干字节 0x00，使消息长度 ≡ 56 mod 64（即留出 8 字节给长度）
 *   3. 在最后 8 字节中写入原始消息的比特长度（大端序 64 位整数）
 *
 * 填充后总长度一定是 512 的倍数，可以完整分块处理。
 *
 * 最后将 8 个 32 位 state 值按大端序输出为 32 字节的哈希值。
 * ========================================================================== */
void sha256_final(SHA256_CTX *ctx, uint8_t hash[32])
{
    uint32_t i = ctx->datalen;

    /* ===== 第一步：添加填充字节 =====
     * 如果当前缓冲区剩余空间足够（< 56 字节），
     * 可以在同一个块中完成填充和长度字段
     */
    if (ctx->datalen < 56)
    {
        /* 添加 0x80 字节（即二进制 1 后跟 7 个 0） */
        ctx->data[i++] = 0x80;
        /* 用 0x00 填充到第 56 字节（留出最后 8 字节给长度） */
        while (i < 56)
            ctx->data[i++] = 0x00;
    }
    else
    {
        /* 当前块剩余空间不足 8 字节，需要两个块 */
        /* 先填满当前块 */
        ctx->data[i++] = 0x80;
        while (i < 64)
            ctx->data[i++] = 0x00;
        /* 处理当前块 */
        sha256_transform(ctx, ctx->data);
        /* 新块的前 56 字节全部填 0 */
        memset(ctx->data, 0, 56);
    }

    /* ===== 第二步：写入消息比特长度（大端序 64 位整数）=====
     * 占用 data[56]~data[63]，共 8 字节
     * bitlen 是 uint64_t，按大端序逐字节写入
     */
    ctx->bitlen += ctx->datalen * 8;   /* 加上最后一轮的字节数 × 8 = 比特数 */
    ctx->data[63] = ctx->bitlen;       /* 最低字节 */
    ctx->data[62] = ctx->bitlen >> 8;
    ctx->data[61] = ctx->bitlen >> 16;
    ctx->data[60] = ctx->bitlen >> 24;
    ctx->data[59] = ctx->bitlen >> 32;
    ctx->data[58] = ctx->bitlen >> 40;
    ctx->data[57] = ctx->bitlen >> 48;
    ctx->data[56] = ctx->bitlen >> 56; /* 最高字节 */

    /* 处理最后一个数据块 */
    sha256_transform(ctx, ctx->data);

    /* ===== 第三步：输出哈希值 =====
     * 将 8 个 32 位 state 值按大端序输出为 32 字节
     * 每个 state[i] 的最高字节先输出（大端序）
     */
    for (i = 0; i < 4; i++)
    {
        hash[i]      = (ctx->state[0] >> (24 - i * 8)) & 0xff;
        hash[i + 4]  = (ctx->state[1] >> (24 - i * 8)) & 0xff;
        hash[i + 8]  = (ctx->state[2] >> (24 - i * 8)) & 0xff;
        hash[i + 12] = (ctx->state[3] >> (24 - i * 8)) & 0xff;
        hash[i + 16] = (ctx->state[4] >> (24 - i * 8)) & 0xff;
        hash[i + 20] = (ctx->state[5] >> (24 - i * 8)) & 0xff;
        hash[i + 24] = (ctx->state[6] >> (24 - i * 8)) & 0xff;
        hash[i + 28] = (ctx->state[7] >> (24 - i * 8)) & 0xff;
    }
}
